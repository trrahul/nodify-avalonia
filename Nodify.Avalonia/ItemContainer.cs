namespace Nodify.Avalonia
{
    /// <summary>
    /// Delegate used to notify when an <see cref="ItemContainer"/> is previewing a new location.
    /// </summary>
    /// <param name="newLocation">The new location.</param>
    public delegate void PreviewLocationChanged(Point newLocation);

    /// <summary>
    /// The container for all the items generated by the <see cref="ItemsControl.ItemsSource"/> of the <see cref="NodifyEditor"/>.
    /// </summary>
    [PseudoClasses(IsSelectedPseudoClass, IsPreviewingSelectablePseudoClass, KeyboardFocusPseudoClass, PendingConnection.IsOverElementPseudoClass)]
    public class ItemContainer : ContentControl, INodifyCanvasItem, IKeyboardFocusTarget<ItemContainer>
    {
        private const string IsSelectedPseudoClass = ":isselected";
        private const string IsPreviewingSelectablePseudoClass = ":ispreviewingselectable";
        private const string KeyboardFocusPseudoClass = ":keyboardfocus";
        #region Dependency Properties
        public static readonly StyledProperty<IBrush> HighlightBrushProperty = AvaloniaProperty.Register<ItemContainer,IBrush>(nameof(HighlightBrush));
        public static readonly StyledProperty<IBrush> SelectedBrushProperty = AvaloniaProperty.Register<ItemContainer,IBrush>(nameof(SelectedBrush));
        public static readonly StyledProperty<Thickness> SelectedBorderThicknessProperty = AvaloniaProperty.Register<ItemContainer, Thickness>(nameof(SelectedBorderThickness), new Thickness(2));
        public static readonly DirectProperty<ItemContainer, Thickness> SelectedMarginProperty =
            AvaloniaProperty.RegisterDirect<ItemContainer, Thickness>(nameof(SelectedMargin), o => o.SelectedMargin);
        public static readonly StyledProperty<bool> IsSelectableProperty = AvaloniaProperty.Register<ItemContainer,bool>(nameof(IsSelectable),true);
        public static readonly StyledProperty<bool> IsSelectedProperty =
            SelectingItemsControl.IsSelectedProperty.AddOwner<ItemContainer>();
        public static readonly DirectProperty<ItemContainer, bool?> IsPreviewingSelectionProperty =
            AvaloniaProperty.RegisterDirect<ItemContainer, bool?>(nameof(IsPreviewingSelection),o => o.IsPreviewingSelection);
        public static readonly StyledProperty<Point> LocationProperty = AvaloniaProperty.Register<ItemContainer,Point>(nameof(Location),defaultBindingMode:BindingMode.TwoWay);
        public static readonly StyledProperty<Point> PreviewLocationProperty = AvaloniaProperty.Register<ItemContainer,Point>(nameof(PreviewLocation),defaultBindingMode:BindingMode.TwoWay);
        public static readonly StyledProperty<Size> ActualSizeProperty = AvaloniaProperty.Register<ItemContainer,Size>(nameof(ActualSize));
        public static readonly DirectProperty<ItemContainer,Size?> DesiredSizeForSelectionProperty = AvaloniaProperty.RegisterDirect<ItemContainer,Size?>(nameof(DesiredSizeForSelection),o => o.DesiredSizeForSelection);
        public static readonly DirectProperty<ItemContainer,bool> IsPreviewingLocationProperty = AvaloniaProperty.RegisterDirect<ItemContainer, bool>(nameof(IsPreviewingLocation),o => o.IsPreviewingLocation);
        public static readonly StyledProperty<bool> IsDraggableProperty = AvaloniaProperty.Register<ItemContainer,bool>(nameof(IsDraggable), true);
        public static readonly StyledProperty<bool> HasCustomContextMenuProperty =
            NodifyEditor.HasCustomContextMenuProperty.AddOwner<ItemContainer>();

        /// <summary>
        /// Gets or sets the brush used when the <see cref="PendingConnection.IsOverElementProperty"/> attached property is true for this <see cref="ItemContainer"/>.
        /// </summary>
        public IBrush HighlightBrush
        {
            get => GetValue(HighlightBrushProperty);
            set => SetValue(HighlightBrushProperty, value);
        }

        /// <summary>
        /// Gets or sets the brush used when <see cref="IsSelected"/> or <see cref="IsPreviewingSelection"/> is true.
        /// </summary>
        public IBrush SelectedBrush
        {
            get => GetValue(SelectedBrushProperty);
            set => SetValue(SelectedBrushProperty, value);
        }

        /// <summary>
        /// Gets or sets the border thickness used when <see cref="IsSelected"/> or <see cref="IsPreviewingSelection"/> is true.
        /// </summary>
        public Thickness SelectedBorderThickness
        {
            get => GetValue(SelectedBorderThicknessProperty);
            set => SetValue(SelectedBorderThicknessProperty, value);
        }

        /// <summary>
        /// Gets the margin used to offset the extra <see cref="SelectedBorderThickness"/> so the container's
        /// bounds stay visually aligned with its unselected <see cref="TemplatedControl.BorderThickness"/>.
        /// </summary>
        public Thickness SelectedMargin
        {
            get => _selectedMargin;
            private set => SetAndRaise(SelectedMarginProperty, ref _selectedMargin, value);
        }

        private void UpdateSelectedMargin()
        {
            Thickness borderThickness = BorderThickness;
            Thickness selectedBorderThickness = SelectedBorderThickness;
            SelectedMargin = new Thickness(
                borderThickness.Left - selectedBorderThickness.Left,
                borderThickness.Top - selectedBorderThickness.Top,
                borderThickness.Right - selectedBorderThickness.Right,
                borderThickness.Bottom - selectedBorderThickness.Bottom);
        }

        /// <summary>
        /// Gets or sets the location of this <see cref="ItemContainer"/> inside the <see cref="NodifyEditor"/> in graph space coordinates.
        /// </summary>
        public Point Location
        {
            get => (Point)GetValue(LocationProperty);
            set => SetValue(LocationProperty, value);
        }
        
        /// <summary>
        /// Gets or sets the preview location of this <see cref="ItemContainer"/> inside the <see cref="NodifyEditor"/> in graph space coordinates.
        /// </summary>
        public Point PreviewLocation
        {
            get => (Point)GetValue(PreviewLocationProperty);
            set => SetValue(PreviewLocationProperty, value);
        }

        /// <summary>
        /// Gets or sets a value that indicates whether this <see cref="ItemContainer"/> is selected.
        /// Can only be set if <see cref="IsSelectable"/> is true.
        /// </summary>
        public bool IsSelected
        {
            get => (bool)GetValue(IsSelectedProperty);
            set => SetValue(IsSelectedProperty, value);
        }

        /// <summary>
        /// Gets a value indicating whether this <see cref="ItemContainer"/> is about to change its <see cref="IsSelected"/> state.
        /// </summary>
        public bool? IsPreviewingSelection
        {
            get => _isPreviewingSelection;
            internal set
            {
                if (SetAndRaise(IsPreviewingSelectionProperty, ref _isPreviewingSelection, value))
                {
                    PseudoClasses.Set(IsPreviewingSelectablePseudoClass, value == null);
                }
            }
        }

        /// <summary>
        /// Gets or sets whether this <see cref="ItemContainer"/> can be selected.
        /// </summary>
        public bool IsSelectable
        {
            get => (bool)GetValue(IsSelectableProperty);
            set => SetValue(IsSelectableProperty, value);
        }

        /// <summary>
        /// Gets a value indicating whether this <see cref="ItemContainer"/> is previewing a new location but didn't logically move there.
        /// </summary>
        public bool IsPreviewingLocation
        {
            get => _isPreviewingLocation;
            protected internal set => SetAndRaise(IsPreviewingLocationProperty,ref _isPreviewingLocation, value);
        }

        /// <summary>
        /// Gets the actual size of this <see cref="ItemContainer"/>.
        /// </summary>
        public Size ActualSize
        {
            get => (Size)GetValue(ActualSizeProperty);
            set => SetValue(ActualSizeProperty, value);
        }

        /// <summary>
        /// Overrides the size to check against when calculating if this <see cref="ItemContainer"/> can be part of the current <see cref="NodifyEditor.SelectedArea"/>.
        /// Defaults to <see cref="Visual.Bounds"/>'s <see cref="Rect.Size"/>.
        /// </summary>
        public Size? DesiredSizeForSelection
        {
            get => _desiredSizeForSelection;
            set => SetAndRaise(DesiredSizeForSelectionProperty,ref _desiredSizeForSelection, value);
        }

        /// <summary>
        /// Gets or sets whether this <see cref="ItemContainer"/> can be dragged.
        /// </summary>
        public bool IsDraggable
        {
            get => (bool)GetValue(IsDraggableProperty);
            set => SetValue(IsDraggableProperty, value);
        }

        private static void OnLocationChanged(ItemContainer itemContainer, AvaloniaPropertyChangedEventArgs<Point> args)
        {
            itemContainer.OnLocationChanged();
            // Guard on IsLoaded so a Location change during teardown/recycle doesn't dereference a
            // null ItemsHost (ItemsHost is null-forgiving).
            if (itemContainer.Editor.IsLoaded && !itemContainer.Editor.IsBulkUpdatingItems)
            {
                itemContainer.Editor.ItemsHost.InvalidateArrange();
            }
        }

        #endregion

        #region Routed Events

        
        public static readonly RoutedEvent DragStartedEvent = RoutedEvent.Register<ItemContainer,VectorEventArgs>(nameof(DragStarted),RoutingStrategies.Bubble);
        public static readonly RoutedEvent DragCompletedEvent = RoutedEvent.Register<ItemContainer,DragCompletedEventArgs>(nameof(DragCompleted),RoutingStrategies.Bubble);
        public static readonly RoutedEvent DragDeltaEvent = RoutedEvent.Register<ItemContainer,VectorEventArgs>(nameof(DragDelta),RoutingStrategies.Bubble);
        public static readonly RoutedEvent IsSelectedChangedEvent = SelectingItemsControl.IsSelectedChangedEvent;
        public static readonly RoutedEvent LocationChangedEvent = RoutedEvent.Register<ItemContainer,RoutedEventArgs>(nameof(LocationChanged),RoutingStrategies.Bubble);

        /// <summary>
        /// Occurs when the <see cref="Location"/> of this <see cref="ItemContainer"/> is changed.
        /// </summary>
        public event EventHandler<RoutedEventArgs> LocationChanged
        {
            add => AddHandler(LocationChangedEvent, value);
            remove => RemoveHandler(LocationChangedEvent, value);
        }

        /// <summary>
        /// Occurs when this <see cref="ItemContainer"/> is the instigator of a drag operation.
        /// </summary>
        public event EventHandler<VectorEventArgs> DragStarted
        {
            add => AddHandler(DragStartedEvent, value);
            remove => RemoveHandler(DragStartedEvent, value);
        }

        /// <summary>
        /// Occurs when this <see cref="ItemContainer"/> is being dragged.
        /// </summary>
        public event EventHandler<VectorEventArgs> DragDelta
        {
            add => AddHandler(DragDeltaEvent, value);
            remove => RemoveHandler(DragDeltaEvent, value);
        }

        /// <summary>
        /// Occurs when this <see cref="ItemContainer"/> completed the drag operation.
        /// </summary>
        public event EventHandler<DragCompletedEventArgs> DragCompleted
        {
            add => AddHandler(DragCompletedEvent, value);
            remove => RemoveHandler(DragCompletedEvent, value);
        }

        /// <summary>
        /// Raises the <see cref="LocationChangedEvent"/> and sets <see cref="IsPreviewingLocation"/> to false.
        /// </summary>
        protected void OnLocationChanged()
        {
            IsPreviewingLocation = false;
            RaiseEvent(new RoutedEventArgs(LocationChangedEvent, this));
        }

        /// <summary>
        /// Raises the <see cref="IsSelectedChangedEvent"/> based on <paramref name="isSelected"/>.
        /// Called when the <see cref="IsSelected"/> value is changed.
        /// </summary>
        /// <param name="isSelected">True if selected, false otherwise.</param>
        protected void OnSelectedChanged(bool isSelected)
        {
            if (!Editor.IsSelecting)
            {
                RaiseEvent(new RoutedEventArgs(IsSelectedChangedEvent ,this ));
            }
        }

        private static void OnIsSelectedChanged(ItemContainer itemContainer, AvaloniaPropertyChangedEventArgs<bool> args)
        {
            bool result = itemContainer.IsSelectable && args.NewValue.Value;
            itemContainer.IsSelected = result;
            itemContainer.OnSelectedChanged(result);
            // Use the coerced result, not the raw new value, so a non-selectable container never
            // shows the :isselected pseudo-class.
            itemContainer.PseudoClasses.Set(IsSelectedPseudoClass, result);
        }

        #endregion

        #region Fields

        /// <summary>
        /// Gets or sets whether right-clicking a container participates in selection even when the
        /// container has no <see cref="Control.ContextMenu"/>. When false (default),
        /// right-click only selects a container that has a context menu (so the menu applies to it).
        /// </summary>
        public static bool PreserveSelectionOnRightClick { get; set; }

        /// <summary>
        /// Gets or sets whether this container draws a custom context menu (not via <see cref="Control.ContextMenu"/>).
        /// Used to suppress starting an interaction so the context menu can appear.
        /// </summary>
        public bool HasCustomContextMenu
        {
            get => (bool)GetValue(HasCustomContextMenuProperty);
            set => SetValue(HasCustomContextMenuProperty, value);
        }

        /// <summary>
        /// Gets whether this container has a context menu (either a <see cref="Control.ContextMenu"/> or a <see cref="HasCustomContextMenu"/>).
        /// </summary>
        public bool HasContextMenu => ContextMenu != null || HasCustomContextMenu;

        /// <summary>
        /// The <see cref="NodifyEditor"/> that owns this <see cref="ItemContainer"/>.
        /// </summary>
        public NodifyEditor Editor { get; }

        /// <summary>
        /// Gets the effective gesture mappings for this container (per-editor override or global fallback).
        /// </summary>
        public EditorGestures ActualGestures => Editor?.ActualGestures ?? EditorGestures.Mappings;

        /// <summary>
        /// The input processor that dispatches pointer/key events to the
        /// <see cref="InputElementStateStack{TElement}"/>-based container states.
        /// </summary>
        protected InputProcessor InputProcessor { get; } = new InputProcessor();

        #endregion

        /// <summary>
        /// Occurs when the <see cref="ItemContainer"/> is previewing a new location.
        /// </summary>
        public event PreviewLocationChanged? PreviewLocationChanged;

        /// <summary>
        /// Raises the <see cref="PreviewLocationChanged"/> event and sets the <see cref="IsPreviewingLocation"/> property to true.
        /// </summary>
        /// <param name="newLocation">The new location.</param>
        protected internal void OnPreviewLocationChanged(Point newLocation)
        {
            IsPreviewingLocation = true;
            PreviewLocationChanged?.Invoke(newLocation);
        }

        #region IKeyboardFocusTarget<ItemContainer>

        // Visual.Bounds and IKeyboardFocusTarget.Bounds would clash if both were named "Bounds".
        // Use explicit interface implementation to expose the graph-space focus bounds without a conflict.
        global::Avalonia.Rect IKeyboardFocusTarget<ItemContainer>.Bounds
            => new global::Avalonia.Rect(Location, DesiredSizeForSelection ?? Bounds.Size);

        ItemContainer IKeyboardFocusTarget<ItemContainer>.Element => this;

        #endregion

        #region Dragging API

        /// <inheritdoc cref="NodifyEditor.BeginDragging()" />
        /// <remarks>Replaces the selection if the container is not selected.</remarks>
        public void BeginDragging()
        {
            if (!IsSelected)
            {
                Select(SelectionHelper.SelectionType.Replace);
            }

            Editor.BeginDragging();
        }

        /// <inheritdoc cref="NodifyEditor.UpdateDragging(Vector)" />
        public void UpdateDragging(Vector amount)
            => Editor.UpdateDragging(amount);

        /// <inheritdoc cref="NodifyEditor.EndDragging" />
        public void EndDragging()
            => Editor.EndDragging();

        /// <inheritdoc cref="NodifyEditor.CancelDragging" />
        public void CancelDragging()
            => Editor.CancelDragging();

        #endregion

        #region Selection API

        /// <summary>
        /// Modifies the selection state of this container based on the specified <paramref name="type"/>.
        /// </summary>
        public void Select(SelectionHelper.SelectionType type)
        {
            switch (type)
            {
                case SelectionHelper.SelectionType.Append:
                    IsSelected = true;
                    break;
                case SelectionHelper.SelectionType.Remove:
                    IsSelected = false;
                    break;
                case SelectionHelper.SelectionType.Invert:
                    IsSelected = !IsSelected;
                    break;
                case SelectionHelper.SelectionType.Replace:
                    // Replace: deselect all nodes AND connections (mutual exclusion), then select this one.
                    Editor.UnselectAll();
                    Editor.UnselectAllConnections();
                    IsSelected = true;
                    break;
            }
        }

        #endregion

        static ItemContainer()
        {
            FocusableProperty.OverrideMetadata(typeof(ItemContainer), new StyledPropertyMetadata<bool>(true));
            IsSelectedProperty.Changed.AddClassHandler<ItemContainer, bool>(OnIsSelectedChanged);
            LocationProperty.Changed.AddClassHandler<ItemContainer, Point>(OnLocationChanged);
            PendingConnection.IsOverElementProperty.Changed.AddClassHandler<ItemContainer, bool>((o, e) =>
                o.PseudoClasses.Set(PendingConnection.IsOverElementPseudoClass, e.NewValue.Value));
            BorderThicknessProperty.Changed.AddClassHandler<ItemContainer, Thickness>((o, e) => o.UpdateSelectedMargin());
            SelectedBorderThicknessProperty.Changed.AddClassHandler<ItemContainer, Thickness>((o, e) => o.UpdateSelectedMargin());
        }

        /// <summary>
        /// Constructs an instance of an <see cref="ItemContainer"/> in the specified <see cref="NodifyEditor"/>.
        /// </summary>
        /// <param name="editor"></param>
        public ItemContainer(NodifyEditor editor)
        {
            Editor = editor;
            InputProcessor.AddSharedHandlers(this);
            SizeChanged += OnRenderSizeChanged;
            UpdateSelectedMargin();

            // IsPreviewingSelection starts null (no preview cycle in progress), and its setter
            // only flips the pseudo-class in response to a value CHANGE — so without this, a
            // container that is click-selected directly (never previewed) never gets the
            // pseudo-class set and the themed selected-border selector
            // (^[IsSelected=True]:ispreviewingselectable`) never matches.
            PseudoClasses.Set(IsPreviewingSelectablePseudoClass, true);
        }

        /// <inheritdoc />
        protected override void OnDetachedFromVisualTree(VisualTreeAttachmentEventArgs e)
        {
            // Focus-trap: if this container is removed from the visual tree while it (or a
            // descendant) holds keyboard focus, return focus to the editor so keyboard
            // navigation keeps working instead of escaping the control.
            bool hadKeyboardFocus = IsKeyboardFocusWithin;

            base.OnDetachedFromVisualTree(e);

            if (hadKeyboardFocus)
            {
                Editor.Focus();
            }
        }

        protected override void OnApplyTemplate(TemplateAppliedEventArgs e)
        {
            base.OnApplyTemplate(e);
        }

        private void OnRenderSizeChanged(object? sender, SizeChangedEventArgs args)
        {
            ActualSize = args.NewSize;
        }

        protected override bool RegisterContentPresenter(ContentPresenter presenter)
        {
            return base.RegisterContentPresenter(presenter);
        }

        /// <summary>
        /// Checks if <paramref name="position"/> is selectable.
        /// </summary>
        /// <param name="position">A position relative to this <see cref="ItemContainer"/>.</param>
        /// <returns>True if <paramref name="position"/> is selectable.</returns>
        protected internal virtual bool IsSelectableLocation(Point position)
        {
            Size size = DesiredSizeForSelection ?? Bounds.Size;
            return position.X >= 0 && position.Y >= 0 && position.X <= size.Width && position.Y <= size.Height;
        }

        /// <summary>
        /// Checks if <paramref name="area"/> contains or intersects with this <see cref="ItemContainer"/> taking into consideration the <see cref="DesiredSizeForSelection"/>.
        /// </summary>
        /// <param name="area">The area to check if contains or intersects this <see cref="ItemContainer"/>.</param>
        /// <param name="isContained">If true will check if <paramref name="area"/> contains this, otherwise will check if <paramref name="area"/> intersects with this.</param>
        /// <returns>True if <paramref name="area"/> contains or intersects this <see cref="ItemContainer"/>.</returns>
        public virtual bool IsSelectableInArea(Rect area, bool isContained)
        {
            var bounds = new Rect(Location, DesiredSizeForSelection ?? Bounds.Size);
            return isContained ? area.Contains(bounds) : area.IntersectsWith(bounds);
        }

        #region State Handling

        private bool? _isPreviewingSelection;
        private bool _isPreviewingLocation;
        private Size? _desiredSizeForSelection;
        private Thickness _selectedMargin;

        /// <inheritdoc />
        protected override void OnPointerPressed(PointerPressedEventArgs e)
        {
            // A pointer press must not retain the keyboard focus visual. This runs before the
            // container state can focus the item and before the event bubbles to NodifyEditor,
            // where LastInputWasKeyboard is updated.
            PseudoClasses.Set(KeyboardFocusPseudoClass, false);
            InputProcessor.ProcessEvent(e);
        }

        /// <inheritdoc />
        protected override void OnGotFocus(FocusChangedEventArgs e)
        {
            base.OnGotFocus(e);

            if (ReferenceEquals(e.NewFocusedElement, this))
            {
                PseudoClasses.Set(KeyboardFocusPseudoClass, Editor.LastInputWasKeyboard);
            }
        }

        /// <inheritdoc />
        protected override void OnLostFocus(FocusChangedEventArgs e)
        {
            PseudoClasses.Set(KeyboardFocusPseudoClass, false);
            base.OnLostFocus(e);
        }

        /// <inheritdoc />
        protected override void OnPointerReleased(PointerReleasedEventArgs e)
        {
            InputProcessor.ProcessEvent(e);

            // Release the mouse capture if all the mouse buttons are released and there's no
            // interaction still in progress.
            var props = e.GetPointerPointProperties();
            if (!InputProcessor.RequiresInputCapture && this.IsMouseCaptured(e)
                && !props.IsRightButtonPressed && !props.IsLeftButtonPressed && !props.IsMiddleButtonPressed)
            {
                this.ReleaseMouseCapture(e);
            }
        }

        /// <inheritdoc />
        protected override void OnPointerMoved(PointerEventArgs e)
        {
            InputProcessor.ProcessEvent(e);
        }

        /// <inheritdoc />
        protected override void OnPointerWheelChanged(PointerWheelEventArgs e)
        {
            InputProcessor.ProcessEvent(e);
        }

        /// <inheritdoc />
        protected override void OnPointerCaptureLost(PointerCaptureLostEventArgs e)
        {
            InputProcessor.ProcessEvent(e);
        }

        /// <inheritdoc />
        protected override void OnKeyUp(KeyEventArgs e)
            => InputProcessor.ProcessEvent(e);

        /// <inheritdoc />
        protected override void OnKeyDown(KeyEventArgs e)
            => InputProcessor.ProcessEvent(e);

        #endregion
    }
}
